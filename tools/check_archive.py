def fail(message: str) -> None:
    errors.append(message)


def rel(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def read_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001 - this is a validation script.
        fail(f"{rel(path)}: не удалось прочитать JSON ({exc})")
        return None


def title_ru(item: dict[str, Any]) -> str:
    title = item.get("title")
    if isinstance(title, dict):
        return str(title.get("ru") or "").strip()
    return str(item.get("title_ru") or item.get("name") or "").strip()


def localized_text_present(container: dict[str, Any], key: str = "text") -> bool:
    value = container.get(key)
    if isinstance(value, dict):
        return any(str(value.get(lang) or "").strip() for lang in LANGS)
    return bool(str(value or "").strip())


def split_regions(value: Any) -> list[str]:
    if isinstance(value, list):
        source = value
    else:
        source = str(value or "").replace("，", ",").split(",")
    return [str(region).strip() for region in source if str(region).strip()]


def check_asset(path_value: Any, owner: str) -> None:
    path_text = str(path_value or "").strip()
    if not path_text:
        return
    if path_text.startswith(("http://", "https://", "data:")):
        return
    path = ROOT / path_text
    if not path.exists():
        fail(f"{owner}: не найден файл ассета {path_text}")


def check_languages(item: dict[str, Any], owner: str) -> None:
    languages = item.get("languages")
    if languages is None:
        return
    if not isinstance(languages, list):
        fail(f"{owner}: languages должен быть списком")
        return
    unknown = sorted(set(map(str, languages)) - LANGS)
    if unknown:
        fail(f"{owner}: неизвестные языки в languages: {', '.join(unknown)}")


def check_regions(item: dict[str, Any], owner: str) -> None:
    regions = split_regions(item.get("filter_regions") or item.get("region") or "")
    unknown = sorted(region for region in regions if region not in KNOWN_REGIONS)
    if unknown:
        fail(f"{owner}: неизвестные регионы: {', '.join(unknown)}")


def check_common_index_fields(item: dict[str, Any], owner: str, *, enemy: bool = False) -> None:
    for key in ("search_text", "sort_version", "filter_regions", "filter_type"):
        if key not in item:
            fail(f"{owner}: в индексной записи отсутствует служебное поле {key}")
    if enemy and "enemy_type_keys" not in item:
        fail(f"{owner}: в индексной записи врага отсутствует enemy_type_keys")


def load_indexes() -> dict[str, list[dict[str, Any]]]:
    indexes: dict[str, list[dict[str, Any]]] = {}
    for section in SECTIONS:
        path = DATA_DIR / f"{section}_index.json"
        data = read_json(path)
        if data is None:
            indexes[section] = []
            continue
        if not isinstance(data, list):
            fail(f"{rel(path)}: ожидается список")
            indexes[section] = []
            continue
        indexes[section] = [item for item in data if isinstance(item, dict)]
        if len(indexes[section]) != len(data):
            fail(f"{rel(path)}: все элементы должны быть объектами")
    return indexes


def detail_path(section: str, item_id: str) -> Path:
    return DATA_DIR / section / f"{item_id}.json"


def check_index_and_details(indexes: dict[str, list[dict[str, Any]]]) -> dict[str, dict[str, dict[str, Any]]]:
    details: dict[str, dict[str, dict[str, Any]]] = {section: {} for section in SECTIONS}

    all_global_ids: list[str] = []
    for section, items in indexes.items():
        ids = [str(item.get("id") or "").strip() for item in items]
        for empty_index, item_id in enumerate(ids, start=1):
            if not item_id:
                fail(f"data/{section}_index.json: пустой id в записи #{empty_index}")
        for item_id, count in Counter(ids).items():
            if item_id and count > 1:
                fail(f"data/{section}_index.json: дублирующийся id {item_id}")
        all_global_ids.extend(f"{section}:{item_id}" for item_id in ids if item_id)

        for item in items:
            item_id = str(item.get("id") or "").strip()
            if not item_id:
                continue
            owner = f"data/{section}_index.json#{item_id}"
            if not title_ru(item):
                fail(f"{owner}: пустое русское название")
            check_languages(item, owner)
            check_regions(item, owner)
            check_asset(item.get("icon"), owner)
            check_common_index_fields(item, owner, enemy=(section == "enemies"))
            if section == "stories" and item.get("story_group") == "character_stories" and "character_filters" not in item:
                fail(f"{owner}: в индексной записи персонажа отсутствует character_filters")
            if section == "stories" and len(str(item.get("search_text") or "")) > 1200:
                fail(f"{owner}: stories_index должен быть лёгким, без полного текста истории в search_text")

            path = detail_path(section, item_id)
            if not path.exists():
                fail(f"{owner}: нет detail-файла {rel(path)}")
                continue
            detail = read_json(path)
            if not isinstance(detail, dict):
                fail(f"{rel(path)}: detail-файл должен быть объектом")
                continue
            if str(detail.get("id") or "").strip() != item_id:
                fail(f"{rel(path)}: id detail-файла не совпадает с индексом")
            if section == "stories" and item.get("story_group") == "character_stories":
                index_filters = item.get("character_filters", [])
                detail_filters = detail.get("character_filters", [])
                if index_filters != detail_filters:
                    fail(f"{owner}: character_filters в индексе не совпадают с detail-файлом")
            details[section][item_id] = detail

    for global_id, count in Counter(all_global_ids).items():
        if count > 1:
            fail(f"дублирующийся глобальный id {global_id}")

    return details


def check_lazy_category_indexes(indexes: dict[str, list[dict[str, Any]]]) -> None:
    path = DATA_DIR / "stories_search.json"
    if path.exists():
        fail("data/stories_search.json: общий индекс текстов историй не должен создаваться")

    specs = (
        ("items", "items", "item_group"),
        ("bestiary", "enemies", "enemy_group"),
        ("stories", "stories", "story_group"),
    )
    for folder, section, group_field in specs:
        source = indexes.get(section, [])
        groups = {str(item.get(group_field) or "").strip() for item in source}
        for group in sorted(value for value in groups if value):
            group_path = DATA_DIR / "indexes" / folder / f"{group}.json"
            if not group_path.exists():
                fail(f"{rel(group_path)}: отсутствует ленивый индекс категории")
                continue
            rows = read_json(group_path)
            if not isinstance(rows, list):
                fail(f"{rel(group_path)}: индекс категории должен быть списком")
                continue
            expected_ids = {str(item.get("id") or "") for item in source if item.get(group_field) == group}
            actual_ids = {str(item.get("id") or "") for item in rows if isinstance(item, dict)}
            if actual_ids != expected_ids:
                fail(f"{rel(group_path)}: состав категории не совпадает с полным индексом")



def check_books(books: dict[str, dict[str, Any]]) -> None:
    for item_id, book in books.items():
        owner = f"data/books/{item_id}.json"
        book_type = str(book.get("subtype") or book.get("book_type") or "").strip()
        if book_type and book_type not in KNOWN_BOOK_TYPES:
            fail(f"{owner}: неизвестный тип книги {book_type}")
        volumes = book.get("volumes")
        if not isinstance(volumes, list) or not volumes:
            fail(f"{owner}: книга без частей/томов")
            continue
        declared = book.get("volume_count")
        if isinstance(declared, int) and declared != len(volumes):
            fail(f"{owner}: volume_count={declared}, но частей/томов {len(volumes)}")
        numbers = []
        for volume in volumes:
            if not isinstance(volume, dict):
                fail(f"{owner}: часть/том должен быть объектом")
                continue
            number = volume.get("number")
            numbers.append(number)
            if not localized_text_present(volume):
                fail(f"{owner}: часть/том {number or '?'} без текста")
        duplicates = [str(value) for value, count in Counter(numbers).items() if value is not None and count > 1]
        if duplicates:
            fail(f"{owner}: дублирующиеся номера частей/томов: {', '.join(duplicates)}")


def check_artifacts(artifacts: dict[str, dict[str, Any]]) -> None:
    for item_id, artifact in artifacts.items():
        owner = f"data/artifacts/{item_id}.json"
        parts = artifact.get("parts")
        if not isinstance(parts, list):
            fail(f"{owner}: parts должен быть списком")
            continue

        keys: list[str] = []
        for part in parts:
            if isinstance(part, dict):
                keys.append(str(part.get("key") or "").strip())

        duplicate_keys = sorted(key for key in set(keys) if key and keys.count(key) > 1)
        if duplicate_keys:
            fail(f"{owner}: дублирующиеся части артефакта: {', '.join(duplicate_keys)}")

        # Most artifact sets contain the classic five slots, but Genshin also has
        # one-piece artifacts such as the Prayers circlets.  The archive supports
        # both shapes; anything else is likely an incomplete entry.
        if len(keys) == 5:
            if set(keys) != KNOWN_ARTIFACT_PARTS:
                fail(f"{owner}: сет из 5 артефактов должен содержать части: {', '.join(sorted(KNOWN_ARTIFACT_PARTS))}")
        elif len(keys) == 1:
            if not keys[0]:
                fail(f"{owner}: одиночный артефакт должен иметь ключ части")
        else:
            fail(f"{owner}: артефакт должен содержать 1 или 5 частей, сейчас: {len(keys)}")

        for part in parts:
            if not isinstance(part, dict):
                fail(f"{owner}: часть артефакта должна быть объектом")
                continue
            key = str(part.get("key") or "").strip()
            if not localized_text_present(part):
                fail(f"{owner}: часть {key or '?'} без текста")
            check_asset(part.get("icon"), f"{owner}#{key}")


def check_weapons(weapons: dict[str, dict[str, Any]]) -> None:
    for item_id, weapon in weapons.items():
        owner = f"data/weapons/{item_id}.json"
        weapon_type = str(weapon.get("weapon_type") or weapon.get("type") or "").strip()
        if weapon_type not in KNOWN_WEAPON_TYPES:
            fail(f"{owner}: неизвестный тип оружия {weapon_type or 'пусто'}")
        entry_kind = str(weapon.get("entry_kind") or "weapon").strip()
        if entry_kind not in {"weapon", "skin"}:
            fail(f"{owner}: неизвестный вид оружейной записи {entry_kind or 'пусто'}")
        rarity = weapon.get("rarity")
        if rarity is not None and str(rarity) not in {"1", "2", "3", "4", "5"}:
            fail(f"{owner}: неизвестная редкость оружия {rarity}")
        if not localized_text_present(weapon) and not localized_text_present(weapon, "description"):
            fail(f"{owner}: оружие без текста/описания")


def check_items(items: dict[str, dict[str, Any]], enemies: dict[str, dict[str, Any]]) -> None:
    enemy_ids = set(enemies)
    for item_id, item in items.items():
        owner = f"data/items/{item_id}.json"
        group = str(item.get("item_group") or "").strip()
        if group not in KNOWN_ITEM_GROUPS:
            fail(f"{owner}: неизвестная группа предмета {group or 'пусто'}")

        material_type = str(item.get("material_type") or "").strip()
        if group == "development_materials" and material_type not in KNOWN_DEVELOPMENT_MATERIAL_TYPES:
            fail(f"{owner}: неизвестный material_type {material_type or 'пусто'}")

        item_type = str(item.get("item_type") or "").strip()
        if item_type and item_type not in KNOWN_ITEM_TYPES.get(group, set()):
            fail(f"{owner}: неизвестный item_type {item_type} для группы {group}")

        materials = item.get("materials")
        if materials is not None:
            if not isinstance(materials, list):
                fail(f"{owner}: materials должен быть списком")
            else:
                keys = []
                for material in materials:
                    if not isinstance(material, dict):
                        fail(f"{owner}: материал должен быть объектом")
                        continue
                    key = str(material.get("key") or "").strip()
                    if not key:
                        fail(f"{owner}: материал без key")
                    keys.append(key)
                    if not title_ru(material):
                        fail(f"{owner}: материал {key or '?'} без русского названия")
                    check_asset(material.get("icon"), f"{owner}#{key}")
                duplicates = [key for key, count in Counter(keys).items() if key and count > 1]
                if duplicates:
                    fail(f"{owner}: дублирующиеся key материалов: {', '.join(duplicates)}")

        dropped_by = item.get("dropped_by")
        if dropped_by:
            if not isinstance(dropped_by, list):
                fail(f"{owner}: dropped_by должен быть списком")
            else:
                missing = [str(enemy_id) for enemy_id in dropped_by if str(enemy_id) not in enemy_ids]
                if missing:
                    fail(f"{owner}: битые ссылки dropped_by: {', '.join(missing)}")

        dropped_by_enemies = item.get("dropped_by_enemies")
        if dropped_by_enemies is not None:
            if not isinstance(dropped_by_enemies, list):
                fail(f"{owner}: dropped_by_enemies должен быть списком")
            else:
                for enemy in dropped_by_enemies:
                    if not isinstance(enemy, dict):
                        fail(f"{owner}: dropped_by_enemies должен содержать объекты")
                        continue
                    enemy_id = str(enemy.get("id") or "").strip()
                    if enemy_id and enemy_id not in enemy_ids:
                        fail(f"{owner}: dropped_by_enemies содержит неизвестного врага {enemy_id}")
                    check_asset(enemy.get("icon"), f"{owner}#enemy:{enemy_id}")


def check_stories(stories: dict[str, dict[str, Any]]) -> None:
    for item_id, story in stories.items():
        owner = f"data/stories/{item_id}.json"
        story_group = str(story.get("story_group") or story.get("category_type") or "").strip()
        if story_group not in KNOWN_STORY_GROUPS:
            fail(f"{owner}: неизвестная группа истории {story_group or '—'}")
        if story_group == "character_stories":
            elements_raw = story.get("elements")
            if isinstance(elements_raw, list):
                elements = [str(value).strip() for value in elements_raw if str(value).strip()]
            else:
                element = str(story.get("element") or "").strip()
                elements = [element] if element else []

            unknown_elements = sorted(value for value in elements if value not in KNOWN_STORY_ELEMENTS)
            if not elements or unknown_elements:
                got = ", ".join(unknown_elements or elements) or "пусто"
                fail(f"{owner}: история персонажа должна иметь element/elements из списка, получено {got}")
            character_filters_raw = story.get("character_filters", [])
            if isinstance(character_filters_raw, list):
                character_filters = [str(value).strip() for value in character_filters_raw if str(value).strip()]
            else:
                character_filters = [str(character_filters_raw).strip()] if str(character_filters_raw or "").strip() else []
            unknown_character_filters = sorted(value for value in character_filters if value not in KNOWN_CHARACTER_FILTERS)
            if unknown_character_filters:
                fail(f"{owner}: неизвестный фильтр персонажа {', '.join(unknown_character_filters)}")

            rarity = story.get("rarity")
            if str(rarity) not in {"4", "5"}:
                fail(f"{owner}: история персонажа должна иметь rarity 4 или 5, получено {rarity or 'пусто'}")
        if story_group in QUEST_STORY_GROUPS:
            continue
        if not localized_text_present(story):
            fail(f"{owner}: история без текста")


def check_quest_corpus(stories: dict[str, dict[str, Any]]) -> None:
    quests = {item_id: item for item_id, item in stories.items() if item.get("story_group") in QUEST_STORY_GROUPS}
    quest_ids = set(quests)

    # The quest corpus is intentionally dynamic: new quests are added over time,
    # so fixed per-category counts would turn every legitimate addition/removal
    # into a CI failure. Instead, compare the generated JSON corpus with the
    # Markdown source files by exact quest IDs.
    generated_ids_by_group = {
        group: {item_id for item_id, item in quests.items() if item.get("story_group") == group}
        for group in QUEST_STORY_GROUPS
    }
    source_ids_by_group: dict[str, set[str]] = {group: set() for group in QUEST_STORY_GROUPS}
    source_id_paths: dict[str, list[Path]] = {}

    quests_root = ROOT / "content" / "stories" / "quests"
    for group in sorted(QUEST_STORY_GROUPS):
        group_dir = quests_root / group
        if not group_dir.exists():
            # Группа может быть временно пустой, например перед импортом новых глав.
            continue

        for path in sorted(group_dir.glob("*.md")):
            markdown = path.read_text(encoding="utf-8")

            id_match = re.search(r"^#\s*id\s*:\s*(.+?)\s*$", markdown, re.MULTILINE)
            if not id_match:
                fail(f"{rel(path)}: quest Markdown has no # id field")
                continue
            item_id = id_match.group(1).strip()
            if not item_id:
                fail(f"{rel(path)}: quest Markdown has an empty # id field")
                continue

            source_ids_by_group[group].add(item_id)
            source_id_paths.setdefault(item_id, []).append(path)

            group_match = re.search(r"^#\s*story_group\s*:\s*(.+?)\s*$", markdown, re.MULTILINE)
            declared_group = group_match.group(1).strip() if group_match else ""
            if declared_group != group:
                fail(
                    f"{rel(path)}: story_group={declared_group or 'пусто'}, "
                    f"но файл лежит в категории {group}"
                )

            if item_id in FORBIDDEN_QUEST_IDS:
                fail(f"{rel(path)}: служебный beta/test quest {item_id} не должен публиковаться")

    for item_id, paths in sorted(source_id_paths.items()):
        if len(paths) > 1:
            locations = ", ".join(rel(path) for path in paths)
            fail(f"quest corpus: duplicate Markdown id {item_id}: {locations}")

    for item_id in sorted(FORBIDDEN_QUEST_IDS & quest_ids):
        fail(f"data/stories/{item_id}.json: служебный beta/test quest не должен попадать в собранный архив")

    # Compare source and generated data per category. This catches stale builds,
    # accidental deletions, additions that were not rebuilt, and quests placed
    # in the wrong category without relying on a hard-coded file count.
    for group in sorted(QUEST_STORY_GROUPS):
        source_ids = source_ids_by_group[group]
        generated_ids = generated_ids_by_group[group]

        missing_from_build = sorted(source_ids - generated_ids)
        stale_in_build = sorted(generated_ids - source_ids)
        if missing_from_build:
            fail(
                f"quest corpus/{group}: Markdown quests missing from generated data: "
                + ", ".join(missing_from_build[:10])
            )
        if stale_in_build:
            fail(
                f"quest corpus/{group}: generated quests have no Markdown source: "
                + ", ".join(stale_in_build[:10])
            )

    if (DATA_DIR / "lore_corpus").exists():
        fail("data/lore_corpus: obsolete parallel JSON corpus must not exist")

    for item_id, quest in quests.items():
        owner = f"data/stories/{item_id}.json"
        display_category = str(quest.get("display_category") or "").strip()
        if not display_category:
            fail(f"{owner}: отсутствует уточнённая классификация задания")
        if re.search(r"[{}<>]|<!--|/20\d{2}-\d{2}-\d{2}", display_category):
            fail(f"{owner}: в классификации задания осталась служебная разметка")

        region = str(quest.get("region") or "").strip()
        if region == "Тейват":
            fail(f"{owner}: для задания должен быть указан конкретный регион, а не Тейват")

        if quest.get("story_group") == "legend_quests" and str(quest.get("rarity") or "") not in {"4", "5"}:
            fail(f"{owner}: задание Легенд должно иметь rarity 4 или 5")

        version = str(quest.get("game_version") or "").strip()
        if not re.fullmatch(r"\d+\.\d+(?:\.\d+)?", version):
            fail(f"{owner}: missing verified release version")
        if version not in [str(value) for value in quest.get("release_versions", [])]:
            fail(f"{owner}: game_version is not present in release_versions")

        parts = quest.get("parts")
        if not isinstance(parts, list) or not parts:
            fail(f"{owner}: quest has no parts")
        else:
            for number, part in enumerate(parts, start=1):
                title = part.get("title") if isinstance(part, dict) and isinstance(part.get("title"), dict) else {}
                text = part.get("text") if isinstance(part, dict) and isinstance(part.get("text"), dict) else {}
                for lang in LANGS:
                    localized_title = str(title.get(lang) or "").strip()
                    localized_text = str(text.get(lang) or "").strip()
                    if not localized_title or not localized_text:
                        fail(f"{owner}#part-{number}: missing {lang} title or text")
                    if TECHNICAL_TEXT_PATTERN.search(localized_title) or TECHNICAL_TEXT_PATTERN.search(localized_text):
                        fail(f"{owner}#part-{number}: technical placeholder remains in {lang}")

                dialogue_counts = {
                    lang: len(re.findall(r"^\*\*[^\n]+:\*\*|^- \*\*", str(text.get(lang) or ""), flags=re.M))
                    for lang in LANGS
                }
                largest_count = max(dialogue_counts.values(), default=0)
                smallest_count = min(dialogue_counts.values(), default=0)
                if largest_count >= 10 and smallest_count < largest_count * 0.6:
                    fail(f"{owner}#part-{number}: probable truncated localization {dialogue_counts}")

        quest_collections = quest.get("quest_collections", [])
        if not isinstance(quest_collections, list):
            fail(f"{owner}: quest_collections must be a list")
        else:
            unknown_collections = sorted(str(value) for value in quest_collections if str(value) not in KNOWN_QUEST_COLLECTIONS)
            if unknown_collections:
                fail(f"{owner}: unknown quest collections {', '.join(unknown_collections)}")
            if any(value in quest_collections for value in ("witch_homework", "witch_revelation")) and quest.get("story_group") != "world_quests":
                fail(f"{owner}: Witch's Homework must remain a world-quest collection")

        for field in ("previous_quests", "next_quests", "related_quests", "quest_chain"):
            values = quest.get(field)
            if not isinstance(values, list):
                fail(f"{owner}: {field} must be a list")
                continue
            if len(values) != len(set(map(str, values))):
                fail(f"{owner}: duplicate IDs in {field}")
            missing = sorted(str(value) for value in values if str(value) not in quest_ids)
            if missing:
                fail(f"{owner}: broken {field} links: {', '.join(missing[:10])}")

        chain = [str(value) for value in quest.get("quest_chain", [])]
        related = [str(value) for value in quest.get("related_quests", [])]
        if item_id not in chain:
            fail(f"{owner}: quest_chain does not contain itself")
        if related != [value for value in chain if value != item_id]:
            fail(f"{owner}: related_quests differs from quest_chain without itself")

    for item_id, quest in quests.items():
        owner = f"data/stories/{item_id}.json"
        chain = [str(value) for value in quest.get("quest_chain", [])]
        for target in chain:
            if target in quests and [str(value) for value in quests[target].get("quest_chain", [])] != chain:
                fail(f"{owner}: chain differs from linked quest {target}")
        for target in quest.get("previous_quests", []):
            if target in quests and item_id not in quests[target].get("next_quests", []):
                fail(f"{owner}: {target} has no inverse next link")
        for target in quest.get("next_quests", []):
            if target in quests and item_id not in quests[target].get("previous_quests", []):
                fail(f"{owner}: {target} has no inverse previous link")


def check_enemies(enemies: dict[str, dict[str, Any]]) -> None:
    for item_id, enemy in enemies.items():
        owner = f"data/enemies/{item_id}.json"
        group = str(enemy.get("enemy_group") or "").strip()
        if group not in KNOWN_ENEMY_GROUPS:
            fail(f"{owner}: неизвестный enemy_group {group or 'пусто'}")
        enemy_type = str(enemy.get("enemy_type") or "").strip()
        if enemy_type and enemy_type not in KNOWN_ENEMY_TYPES:
            fail(f"{owner}: неизвестный enemy_type {enemy_type}")
        if not localized_text_present(enemy) and not localized_text_present(enemy, "description"):
            fail(f"{owner}: враг без текста/описания")
        drops = enemy.get("drops")
        if drops is not None and not isinstance(drops, list):
            fail(f"{owner}: drops должен быть списком")
        check_asset(enemy.get("icon"), owner)


def check_summary(indexes: dict[str, list[dict[str, Any]]]) -> None:
    path = DATA_DIR / "archive_summary.json"
    if not path.exists():
        fail("data/archive_summary.json: файл отсутствует")
        return
    summary = read_json(path)
    if not isinstance(summary, dict):
        fail("data/archive_summary.json: ожидается объект")
        return
    for section, items in indexes.items():
        expected = len(items)
        value = summary.get(section)
        if isinstance(value, dict):
            actual = value.get("count", value.get("total"))
        else:
            actual = value
        if actual is not None and actual != expected:
            fail(f"data/archive_summary.json: {section}={actual}, но в индексе {expected}")

    expected_groups = {
        name: dict(Counter(str(item.get(field) or "") for item in indexes[section]))
        for name, section, field in (
            ("items", "items", "item_group"),
            ("stories", "stories", "story_group"),
            ("bestiary", "enemies", "enemy_group"),
        )
    }
    if summary.get("groups") != expected_groups:
        fail("data/archive_summary.json: счётчики категорий устарели")


def compiled_css_from_sources() -> str | None:
    chunks = [CSS_HEADER.strip()]
    for name in CSS_MODULES:
        path = SRC_CSS_DIR / name
        if not path.exists():
            fail(f"src/css/{name}: CSS-модуль отсутствует")
            return None
        chunks.append(path.read_text(encoding="utf-8").strip())
    return "\n\n".join(chunks).strip() + "\n"


def compiled_js_from_sources() -> str | None:
    chunks = [JS_HEADER.strip(), "(() => {", '  "use strict";']
    for name in JS_MODULES:
        path = SRC_JS_DIR / name
        if not path.exists():
            fail(f"src/js/{name}: JS-модуль отсутствует")
            return None
        module = path.read_text(encoding="utf-8").strip()
        indented = "\n".join(f"  {line}" if line else "" for line in module.splitlines())
        chunks.append(f"  // src/js/{name}\n{indented}")
    chunks.append("})();")
    return "\n\n".join(chunks).strip() + "\n"


def check_generated_js() -> None:
    js = ASSETS_DIR / "js" / "archive.js"
    if not js.exists():
        fail("assets/js/archive.js: итоговый JS отсутствует")
        return

    expected = compiled_js_from_sources()
    if expected is not None:
        actual = js.read_text(encoding="utf-8")
        if actual != expected:
            fail("assets/js/archive.js: файл не совпадает со сборкой из src/js/**")

    source_modules = sorted(path.relative_to(SRC_JS_DIR).as_posix() for path in SRC_JS_DIR.rglob("*.js")) if SRC_JS_DIR.exists() else []
    if source_modules != sorted(JS_MODULES):
        fail("src/js: набор JS-модулей отличается от ожидаемого списка сборки")


def check_generated_css() -> None:
    """Проверяем только актуальность сборки, не запрещая автору выбирать CSS-приёмы."""
    css = ASSETS_DIR / "css" / "archive.css"
    if not css.exists():
        fail("assets/css/archive.css: итоговый CSS отсутствует")
        return
    expected = compiled_css_from_sources()
    if expected is not None and css.read_text(encoding="utf-8") != expected:
        fail("assets/css/archive.css: файл не совпадает со сборкой из src/css/*.css")


def check_content_structure() -> None:
    if (ASSETS_DIR / "icons" / "hystory").exists():
        fail("assets/icons/hystory: опечатка в названии папки; используйте assets/icons/stories/character")
    if (ASSETS_DIR / "icons" / "history").exists():
        fail("assets/icons/history: папка переименована; используйте assets/icons/stories/character")


    content_root = ROOT / "content"
    if not content_root.exists():
        return

    stories_content_root = content_root / "stories"
    if list(stories_content_root.glob("*.md")):
        fail("content/stories: Markdown files must live under character_stories/ or quests/")

    for path in sorted(content_root.rglob("*.md")):
        text = path.read_text(encoding="utf-8")
        if re.search(r"^##\s+(NOTES|INTERNAL)\s*$", text, re.MULTILINE):
            fail(f"{rel(path)}: служебные блоки NOTES/INTERNAL должны быть удалены из md")

    # Пустая коллекция допустима; в новых шаблонах дополнительные фильтры необязательны.

    content_items = content_root / "items"
    teapot_dir = content_items / "serenitea_pot"
    teyvat_dir = content_items / "teyvat_resources"

    # Пустые категории — штатное состояние. Git не хранит пустые папки;
    # валидируем содержимое только если оно есть, без .gitkeep и запретов на рост архива.

    if teyvat_dir.exists():
        for path in sorted(teyvat_dir.glob("*.md")):
            text = path.read_text(encoding="utf-8")
            if "# item_group: serenitea_pot" in text or "# item_type: teapot" in text:
                fail(f"{rel(path)}: контент Чайника не должен лежать в Ресурсах Тейвата")

    if teapot_dir.exists():
        teapot_types: set[str] = set()
        for path in sorted(teapot_dir.glob("*.md")):
            text = path.read_text(encoding="utf-8")
            if "# item_group: serenitea_pot" not in text:
                fail(f"{rel(path)}: файл в папке Чайника должен иметь item_group: serenitea_pot")
            match = re.search(r"^#\s*item_type\s*:\s*(.+?)\s*$", text, re.MULTILINE)
            if match:
                teapot_types.add(match.group(1).strip())
        unwanted = teapot_types - {"blueprint"}
        if unwanted:
            fail(f"content/items/serenitea_pot: после лорной очистки допускаются только чертежи: {', '.join(sorted(unwanted))}")


def check_infrastructure_files() -> None:
    required = [".gitattributes", ".editorconfig", ".gitignore", ".nojekyll"]
    for name in required:
        if not (ROOT / name).exists():
            fail(f"{name}: файл отсутствует")

    nojekyll = ROOT / ".nojekyll"
    if nojekyll.exists() and nojekyll.read_text(encoding="utf-8") not in {"", "\n"}:
        fail(".nojekyll: файл должен быть пустым")

    index = ROOT / "index.html"
    if not index.exists():
        fail("index.html: файл отсутствует")
        return
    text = index.read_text(encoding="utf-8")
    if "публичная база игровых текстов" not in text or "brand-subtitle" not in text:
        fail("index.html: под логотипом должна быть подпись «публичная база игровых текстов»")
    for asset in ("favicon.ico", "favicon.svg", "apple-touch-icon.png"):
        if f"assets/icons/{asset}" not in text or not (ASSETS_DIR / "icons" / asset).is_file():
            fail(f"index.html: отсутствует иконка браузера {asset}")
    if "<title>Архив Лороведьмы</title>" not in text:
        fail("index.html: неверное название проекта")
    versions = CACHE_RE.findall(text)
    if not versions:
        fail("index.html: не найдены cache-busting версии для CSS/JS")
    elif len(set(versions)) != 1:
        fail(f"index.html: версии cache-bust отличаются: {', '.join(versions)}")


def check_line_endings() -> None:
    for path in ROOT.rglob("*"):
        if not path.is_file():
            continue
        if any(part in SKIP_DIRS for part in path.parts):
            continue
        if path.suffix not in TEXT_SUFFIXES and path.name not in TEXT_NAMES:
            continue
        data = path.read_bytes()
        if b"\r\n" in data or b"\r" in data.replace(b"\r\n", b""):
            fail(f"{rel(path)}: найден CRLF/CR, ожидается LF")


def main() -> int:
    # Проверки должны выявлять сломанные данные и несобранные файлы,
    # а не навязывать папки-заглушки, оформление карточек или конкретный код интерфейса.
    check_content_structure()
    check_infrastructure_files()
    check_line_endings()

    if not DATA_DIR.exists():
        fail("data/: папка не найдена. Сначала запустите tools/build_archive.py")
        indexes = {section: [] for section in SECTIONS}
    else:
        indexes = load_indexes()
        details = check_index_and_details(indexes)
        check_lazy_category_indexes(indexes)
        check_quest_corpus(details.get("stories", {}))
        check_books(details.get("books", {}))
        check_artifacts(details.get("artifacts", {}))
        check_weapons(details.get("weapons", {}))
        check_stories(details.get("stories", {}))
        check_enemies(details.get("enemies", {}))
        check_items(details.get("items", {}), details.get("enemies", {}))
        check_summary(indexes)
    errors.extend(check_bot_indexes())
    check_generated_css()
    check_generated_js()

    if errors:
        print("Проверка архива: найдены ошибки", file=sys.stderr)
        for message in errors:
            print(f"- {message}", file=sys.stderr)
        return 1

    counts = ", ".join(f"{section}: {len(indexes.get(section, []))}" for section in SECTIONS)
    print(f"Проверка архива: OK ({counts})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
